"""Generate AEW's bundled price table from OpenCode's model catalog (register F25, plan U2).

``aew init`` copies ``src/aew/policy/default_pricing.yaml``, so init works air-gapped and fast. This tool regenerates
it from the catalog's source, and the table's ``as_of`` says how old its prices are.

    python tools/pricing_table.py --catalog models.json --as-of 2026-11-08

A row is written only for a provider whose token semantics OpenCode's adapter declares: a run on any other route reads
unpriced whatever a table says, so a row for it would be noise. ``aew/pricing/v1`` rows are flat, so a model the catalog
prices higher above a context size gets its base tier and an entry in ``base_tier_only``: every figure using it reads as
a floor. Reasoning is billed at the output rate: the catalog names no rate of its own, and the record's disjoint
semantics split it out of output.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

CATALOG_URL = "https://models.dev/api.json"
OUT = Path(__file__).resolve().parent.parent / "src" / "aew" / "policy" / "default_pricing.yaml"
# provider -> the catalog package its models must carry (None: all). Zen's others speak other protocols: unmeasured.
ROUTES = {"openai": None, "opencode": "@ai-sdk/openai"}


def _row(cost: dict[str, Any]) -> dict[str, float]:
    row = {k: cost[k] for k in ("input", "output", "cache_read", "cache_write") if k in cost}
    row["reasoning"] = cost["output"]
    return row


def build(catalog: dict[str, Any], as_of: str) -> dict[str, Any]:
    prices: dict[str, Any] = {}
    tiers: dict[str, Any] = {}
    for provider, package in ROUTES.items():
        for model, info in sorted(catalog[provider]["models"].items()):
            cost = info.get("cost")
            if not cost or "input" not in cost or "output" not in cost:
                continue
            if package is not None and (info.get("provider") or {}).get("npm") != package:
                continue
            key = f"{provider}/{model}"
            prices[key] = _row(cost)
            sizes = [t["tier"]["size"] for t in cost.get("tiers") or [] if t.get("tier", {}).get("type") == "context"]
            if sizes:
                tiers[key] = {"above_context_tokens": min(sizes)}
    return {"schema": "aew/pricing/v1", "currency": "USD", "as_of": as_of,
            "source": f"OpenCode's model catalog ({CATALOG_URL}), base rates; regenerated by tools/pricing_table.py",
            "base_tier_only": tiers, "prices": prices}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--catalog", required=True, help=f"a saved copy of {CATALOG_URL}")
    parser.add_argument("--as-of", required=True, help="the date the catalog was fetched (YYYY-MM-DD)")
    args = parser.parse_args(argv)
    catalog = json.loads(Path(args.catalog).read_text(encoding="utf-8"))
    from aew.util import dump_yaml

    OUT.write_bytes(dump_yaml(build(catalog, args.as_of)).encode("utf-8"))
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
