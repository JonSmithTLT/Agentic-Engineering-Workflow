"""The ``harness-capabilities`` family: what each harness provides, and what each steering feature needs (steering
design §7).

Read at run time from the owner, ``aew.harness.harness_capabilities``: its ``declarations()`` (each adapter's own
declaration in code, and the recorded column of a harness with no adapter yet) and its ``FEATURES``. A record per
(harness, capability) and per feature; the page renders them as one table. The set is complete by construction: the
declaration test fails when a harness column omits a capability or a feature needs one a harness neither provides nor
marks as a gap with a register row.
"""

from __future__ import annotations

from reference_families import common as C

FAMILY = "harness-capabilities"
FEATURE = "feature"  # the key space of a feature: `feature:<name>`
OWNER = "aew.harness.harness_capabilities"
PAGE = "harness-capabilities.md"
_TESTS = "tests/integration/test_harness_capabilities.py::"  # never a unit module (the fast tier's rule)
CHECKS = (
    _TESTS + "test_every_feature_is_supported_or_a_recorded_gap_on_every_harness",
    _TESTS + "test_every_harness_column_states_every_capability",
    _TESTS + "test_the_opencode_adapter_declares_its_own_column_in_code",
)
# The reference holds no register or requirement id (tests/unit/test_reference.py): a gap's fact says only that its
# declaration names a register row. Where each column is declared: an adapter's own class, or the owner's table.
ANCHORS = {"opencode": ("aew.harness.opencode.adapter", "OpenCodeAdapter"), "codex": (OWNER, "CODEX")}


def build(ctx: C.Context) -> C.Built:
    from aew.harness import harness_capabilities as H

    cov = C.complete(f"{OWNER}:declarations", CHECKS)
    records: list[C.Record] = []
    for harness, column in sorted(H.declarations().items()):
        module, symbol = ANCHORS.get(harness, (OWNER, "declarations"))
        for cap in sorted(column):
            s = column[cap]
            records.append(C.Record(FAMILY, f"{harness}:{cap}", module, symbol, "enumerated", cov,
                                    {"harness": harness, "capability": cap, "status": s.status, "how": s.how,
                                     "register_row": bool(s.register)}))
    for feature, (needs, built_by) in sorted(H.FEATURES.items()):
        records.append(C.Record(FAMILY, f"{FEATURE}:{feature}", OWNER, "FEATURES", "enumerated", cov,
                                {"feature": feature, "needs": ", ".join(needs), "built_by": built_by}))
    return C.Built(records=records, pages={PAGE: page(records, H.CAPABILITIES)})


def page(records: list[C.Record], meanings: dict[str, str]) -> str:
    cells: dict[tuple[str, str], dict] = {}
    harnesses: list[str] = []
    features = []
    for r in records:
        f = r.fact or {}
        if "feature" in f:
            features.append(f)
            continue
        cells[(f["capability"], f["harness"])] = f
        if f["harness"] not in harnesses:
            harnesses.append(f["harness"])

    def cell(f: dict | None) -> str:
        if f is None:
            return "not declared"
        text = f"**{f['status']}**: {f['how']}"
        return text + (" (a register row holds the work)" if f["register_row"] else "")

    lines = ["# Harness capabilities", "",
             "What each harness provides to AEW's steering features, and what each feature needs, read from "
             f"`{OWNER}`: each adapter's own declaration in code, and the recorded column of a harness that has no "
             "adapter yet. A gap is held by a register row, which the declaration names (the reference holds no "
             "register or requirement id). Generated by "
             "`python tools/reference.py render`; do not edit.", "",
             "## Capabilities", "",
             "| Capability | Meaning | " + " | ".join(harnesses) + " |",
             "|---|---|" + "---|" * len(harnesses)]
    for cap in sorted(meanings):
        lines.append(f"| `{cap}` | {meanings[cap]} | "
                     + " | ".join(cell(cells.get((cap, h))) for h in harnesses) + " |")
    lines += ["", "## Features", "", "| Feature | Needs | Built by |", "|---|---|---|"]
    for f in features:
        needs = ", ".join(f"`{n}`" for n in f["needs"].split(", "))
        lines.append(f"| `{f['feature']}` | {needs} | {f['built_by']} |")
    return "\n".join(lines).rstrip("\n") + "\n"
