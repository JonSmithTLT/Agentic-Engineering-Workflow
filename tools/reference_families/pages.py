        "## A record", "",
        "- `family`, and `anchor` (`module` and `symbol`; line numbers churn, so a line is never an anchor).",
        "- `basis`: `enumerated` (read from a registry the code owns, at run time), `declared` (a table the generator "
        "declares, pinned to the code), `static` (read from the source without running it) or `observed` (read back "
        "from something the generator ran).",
        "- `coverage.label`: `complete-by-construction` (names its `registry` and the tests in `check` that stop code "
