"""The two pages that belong to no one family: the directory's README and ``gaps.md`` (STG-12 S12-2).

Both are drawn from the index alone. The README carries no counts (they are measured in ``index.json``), so a change to
one family's records changes that family's page and the index, and nothing else.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any

from reference_families import common as C

GAPS = "gaps.md"
README = "README.md"


def _anchor(module: str, symbol: str | None) -> str:
    return f"`{module}:{symbol}`" if symbol else f"`{module}`"


def unresolved_by_family(index: Mapping[str, Any]) -> dict[str, list[tuple[str, str | None, str]]]:
    """Every unresolved item of the reference, by family: the index's ``gaps``, which is computed from the records."""
    out: dict[str, list[tuple[str, str | None, str]]] = {}
    for gap in index["gaps"]:
        out.setdefault(gap["family"], []).append((gap["module"], gap["symbol"], gap["why"]))
    return {family: sorted(items, key=lambda i: (i[0], i[1] or "", i[2])) for family, items in sorted(out.items())}


def gaps_page(index: Mapping[str, Any]) -> str:
    by_family = unresolved_by_family(index)
    total = sum(len(v) for v in by_family.values())
    lines = ["# Gaps", "",
             "Everything the generator could not resolve, by family: each distinct unresolved item of every record, "
             "whether it is the record's own or one of a list fact's (`fact_coverage`). Each item is anchored by "
             "module and symbol and says why. Nothing is guessed to fill one. Generated by "
             "`python tools/reference.py render`; do not edit.", "",
             f"Unresolved items: **{total}**.", ""]
    for family, items in by_family.items():
        lines += [f"## {family} ({len(items)})", ""]
        lines += [f"- {_anchor(m, s)}: {why}" for m, s, why in items]
        lines.append("")
    if not by_family:
        lines += ["None.", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def readme(index: Mapping[str, Any], pages: Mapping[str, str]) -> str:
    listing = []
    for name in sorted(pages):
        title = pages[name].splitlines()[0].removeprefix("# ").strip()
        listing.append(f"- [{name}]({name}): {title}")
    return "\n".join([
        "# As-built reference (generated)", "",
        "What the code is, enumerated from the code. It states what the code is, never what it should be, and holds "
        "no requirement. Generated by `python tools/reference.py render`; `python tools/reference.py check` "
        "regenerates it in memory and fails on any difference, and CI runs it as a fast-lane test. Do "
        "not edit these files by hand.", "",
        "## Files", "",
        f"- [index.json](index.json): the machine index. `records` is keyed by record id (`<family>:<key>`); `counts` "
        f"measures records per family and per coverage label and the unresolved total, and carries a `digest` of every "
        f"record and gap; `gaps` is a summary computed from the records, every distinct unresolved item once with "
        f"its family (nothing lives only there). Schema `{C.SCHEMA}`.",
        *listing, "",
        "## A record", "",
        "- `family`, and `anchor` (`module` and `symbol`; line numbers churn, so a line is never an anchor).",
        "- `basis`: `enumerated` (read from a registry the code owns, at run time), `declared` (a table the generator "
        "declares, pinned to the code), `static` (read from the source without running it) or `observed` (read back "
        "from something the generator ran).",
        "- `coverage.label`: `complete-by-construction` (names its `registry` and the tests in `check` that stop code "
        "bypassing it), `lower-bound` (lists what it could not resolve in `unresolved`) or `unknown`.",
        "- `fact`: the record's own facts.",
        "- `fact_coverage`: on the record, beside `coverage` (it describes facts, so it is not one). For each list "
        "fact a detector found, an object keyed by the fact's name, in `coverage`'s vocabulary: how complete the "
        "list is. A list fact with no entry is `unknown`, and an empty list never means none.",
        "- A `modules` record also has `imports`, a top-level key: the AEW modules it imports, statically.", "",
        "## When a change moves it", "",
        "A pull request that changes enumerated code (a module, its imports, an entry point, a spawn site) runs "
        "`python tools/reference.py render` and commits `docs/reference/`. After a merge conflict here, take either "
        "side and run `render`: the output is a function of the code, so the second change to merge re-renders. Two "
        "pull requests that both change the records always conflict, on the `digest` line of `counts`, so a clean "
        "merge cannot leave the totals stale.", ""])
