// Compile the exact named schemas once, outside the browser. No unsafe-eval,
// extra dependencies, coercion, defaults or removal of additional fields.
import fs from 'node:fs';
import Ajv from 'ajv';
import { createHash } from 'node:crypto';
import ts from 'typescript';
import { compatibleSchema } from '../src/stg02/schema-compat.ts';

const pins = {
  d01: '50bd04a0e8f10fe70bc43ffebca8a0b3b0e08872b339030d6d8dfebee180ebba',
  'o01-command': '17f28b3f312bf3cb5f9f134803f68909aef1f49827c655c40deef85556c35f09',
  'o01-response': '170621998574a70df8a0b7efce174e0d7b7b4bf94f9282f167c226181cddc51e',
};
const read = name => {
  const bytes = fs.readFileSync(`src/stg02/contracts/${name}.json`);
  if (pins[name] && createHash('sha256').update(bytes).digest('hex') !== pins[name]) throw new Error(`Sealed schema pin mismatch: ${name}`);
  return JSON.parse(bytes);
};
const documents = { d01: read('d01'), commands: read('o01-command'), responses: read('o01-response') };
const specifications = {
  waiting: ['d01', '#/$defs/ReadWaiting'], run: ['d01', '#/$defs/ReadRunDetail'],
  continuation: ['d01', '#/$defs/ReadContinuationVector'], operations: ['d01', '#/$defs/ReadOwnerOperations'],
  d01Problem: ['d01', '#/$defs/Problem'], command: ['commands', '#/$defs/CommandSet'],
  receipt: ['responses', '#/components/schemas/Receipt'], operation: ['responses', '#/components/schemas/OwnerOperationRead'],
  o01Problem: ['responses', '#/components/schemas/Problem'],
};
const ajv = new Ajv({ allErrors: true, jsonPointers: true, validateSchema: false, extendRefs: true, sourceCode: true, format: 'full', inlineRefs: false });
const validators = {};
const compatible = Object.fromEntries(Object.entries(documents).map(([name, doc]) => [name, compatibleSchema(doc)]));
for (const [name, [document, reference]] of Object.entries(specifications)) {
  const parsed = compatible[document];
  validators[name] = ajv.compile({ ...(parsed.$defs ? { $defs: parsed.$defs } : {}),
    ...(parsed.components ? { components: parsed.components } : {}), $ref: reference });
}
const functions = new Map();
function visit(fn) {
  if (functions.has(fn)) return;
  if (!fn.source?.code) throw new Error('Unserializable validator dependency');
  functions.set(fn, functions.size);
  for (const value of fn.refVal) if (typeof value === 'function') visit(value);
}
for (const validator of Object.values(validators)) visit(validator);
const objects = new Map();
const objectCode = [];
function literal(value) {
  if (typeof value === 'function') {
    if (!functions.has(value)) throw new Error('Unknown validator reference');
    return `v${functions.get(value)}`;
  }
  if (value && typeof value === 'object') {
    const key = JSON.stringify(value, (_name, item) => typeof item === 'function' ? { compiledFunction: functions.get(item) } : item);
    if (objects.has(key)) return `object${objects.get(key)}`;
    const index = objects.size;
    objects.set(key, index);
    const expression = Array.isArray(value) ? `[${value.map(literal).join(',')}]` : `{${Object.entries(value).map(([name, child]) => `${JSON.stringify(name)}:${literal(child)}`).join(',')}}`;
    objectCode.push(`const object${index} = ${expression};`);
    return `object${index}`;
  }
  return JSON.stringify(value);
}
const code = [
  '/* eslint-disable */',
  '// Generated by scripts/generate-stg02.mjs from sealed v0.5.4 schema copies; do not edit.',
  "import makeFormats from 'ajv/lib/compile/formats.js';",
  "import equal from 'fast-deep-equal';",
  "import ucs2length from 'ajv/lib/compile/ucs2length.js';",
  "const formats = makeFormats('full');",
];
for (const [, index] of functions) code.push(`let impl${index}; function v${index}(...args) { const result = impl${index}(...args); v${index}.errors = impl${index}.errors; return result; }`);
const metadata = [];
const unsupportedRuntimeNames = new Set(['self', 'RULES', 'customRules', 'ValidationError', 'regExp']);
function checkRuntimeDependencies(source) {
  // Compiler compatibility check, not a sanitizer for arbitrary code. Only the
  // SHA-256-pinned schema inputs above are compiled. Inspect identifier tokens
  // rather than treating a regex over generated source as a security boundary.
  const scanner = ts.createScanner(ts.ScriptTarget.Latest, true, ts.LanguageVariant.Standard, source);
  for (let token = scanner.scan(); token !== ts.SyntaxKind.EndOfFileToken; token = scanner.scan()) {
    if (token === ts.SyntaxKind.Identifier && unsupportedRuntimeNames.has(scanner.getTokenText()))
      throw new Error('Unsupported compiled runtime dependency');
  }
}
for (const [fn, index] of functions) {
  checkRuntimeDependencies(fn.source.code);
  metadata.push(`v${index}.schema = ${literal(fn.schema)}; v${index}.refVal = ${literal(fn.refVal)}; v${index}.root = ${literal(fn.root)};`);
}
const implementations = [];
for (const [fn, index] of functions) implementations.push(`impl${index} = (function(refVal, root, defaults) { ${fn.source.code} })(v${index}.refVal, v${index}.root, ${literal(fn.source.defaults)}); impl${index}.schema = v${index}.schema;`);
code.push(...objectCode, ...metadata, ...implementations);
code.push(`export const validators = {${Object.entries(validators).map(([name, fn]) => `${name}:v${functions.get(fn)}`).join(',')}};`, '');
const output = code.join('\n');
const target = 'src/stg02/validators.generated.js';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('STG-02 validator drift');
} else fs.writeFileSync(target, output);
console.log(`${Object.keys(validators).length} operation schemas, ${functions.size} static validator functions`);
